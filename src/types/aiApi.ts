/**
 * Types for the AI Assistant API (Spring AI & RAG integration).
 *
 * Grounded in backend source:
 * - com.marketplace.controller.AiController
 * - com.marketplace.dto.request.AiAskRequest
 * - com.marketplace.dto.response.AiProductSearchResponse
 * - com.marketplace.dto.response.AiProductQueryResponse
 * - com.marketplace.dto.response.AiProductResponse
 * - com.marketplace.dto.response.AiChatSessionResponse
 * - com.marketplace.dto.response.AiMessageResponse
 * - com.marketplace.enums.AiAnswerSource
 * - com.marketplace.enums.AiRole
 */

/**
 * Indicates who generated the answer in POST /api/v1/ai/ask.
 * - 'AI': generated by Spring AI LLM provider.
 * - 'RULES': generated by rule-based fallback when provider is unconfigured, rate-limited, cooling down, or errored.
 */
export type AiAnswerSource = 'AI' | 'RULES';

/**
 * Role of a message in an AI conversation session.
 * Backend persists 'USER' and 'ASSISTANT' in ai_messages.
 */
export type AiRole = 'USER' | 'ASSISTANT';

/**
 * Request payload for POST /api/v1/ai/ask.
 * - `message`: required question text, max 1000 characters.
 * - `sessionId`: optional for authenticated CUSTOMER (null starts new session); must be null/omitted for guest.
 */
export type AiAskRequest = {
  message: string;
  sessionId?: string | null;
};

/**
 * The catalog query actually executed by the tool or rule engine.
 * Notice: minPrice, maxPrice, minRating are string-formatted decimals from @JsonFormat(shape = Shape.STRING).
 */
export type AiProductQueryResponse = {
  text: string | null;
  category: string | null;
  minPrice: string | null;
  maxPrice: string | null;
  minRating: string | null;
  sort: string | null;
};

/**
 * A product recommendation returned in the AI response.
 * Grounded in actual database catalog records (never hallucinated JSON).
 * Notice: price and ratingAverage are string-formatted decimals from @JsonFormat(shape = Shape.STRING).
 */
export type AiProductResponse = {
  id: string;
  name: string;
  imageUrl: string | null;
  price: string;
  stock: number;
  ratingAverage: string;
  reviewCount: number;
  sellerId: string;
};

/**
 * Response payload for POST /api/v1/ai/ask.
 */
export type AiProductSearchResponse = {
  answer: string;
  query: AiProductQueryResponse | null;
  products: AiProductResponse[];
  sessionId: string | null;
  answeredBy: AiAnswerSource;
};

/**
 * A customer's persisted AI chat session from GET /api/v1/ai/sessions.
 * Sorted newest first. Backend entity does not have title/summary.
 */
export type AiChatSessionResponse = {
  id: string;
  userId: string;
  createdAt: string;
};

/**
 * One message in an AI chat session from GET /api/v1/ai/sessions/{id}/messages.
 * Confidence derives from backend java.math.BigDecimal (numeric or null in JSON).
 */
export type AiMessageResponse = {
  id: string;
  sessionId: string;
  role: AiRole;
  content: string;
  confidence: number | null;
  createdAt: string;
};
